"""Bridge from the Windows client to the Debian CUA loop over the restored secure shell.

The host's loop is the authority for the answer. This module opens a loopback SSH tunnel
through the WSL secure-shell key, reads the loop token from `/etc/agent/loop.env` into
memory, and calls the host's own `/v1/chat/completions`. The token is never written to a
file, printed, put in state, or sent anywhere except that loopback tunnel.

The host is headless. Speech is generated by `voice.py` on the Windows side; this module
only carries the words.
"""

from __future__ import annotations

import datetime
import json
import pathlib
import shlex
import socket
import subprocess
import threading
import time
import urllib.error
import urllib.request

import hosts

ROOT = pathlib.Path(__file__).resolve().parent
DISTRO = "Debian"
HOST = hosts.debian_host()
KEY = "m0/id_ed25519"
LOCAL_PORT = 18777
REMOTE_PORT = 8766
SCHEMA = "popit.axis-bridge/1"


def iso() -> str:
    return datetime.datetime.now(datetime.timezone.utc).replace(microsecond=0).isoformat()


class Refused(Exception):
    def __init__(self, code: str, detail: str = "") -> None:
        super().__init__(f"{code}: {detail}")
        self.code = code
        self.detail = detail

    def as_dict(self) -> dict:
        return {"code": self.code, "detail": self.detail}


def _wsl(remote: str, timeout: float = 15.0) -> subprocess.CompletedProcess:
    """Run one command on the Debian host through the WSL restore key."""
    script = (
        "cd /root; PATH=/usr/bin:/bin /usr/bin/ssh -o BatchMode=yes "
        f"-o ConnectTimeout=5 -i {KEY} root@{HOST} {shlex.quote(remote)}"
    )
    return subprocess.run(
        ["wsl.exe", "-d", DISTRO, "-u", "root", "--", "sh", "-c", script],
        capture_output=True, text=True, encoding="utf-8", errors="replace",
        timeout=timeout, creationflags=0x08000000,
    )


class AxisBridge:
    def __init__(self, port: int = LOCAL_PORT) -> None:
        self.port = port
        self.lock = threading.RLock()
        self._ensure_lock = threading.Lock()
        self.token = ""
        self.process: subprocess.Popen | None = None
        self.state = "idle"
        self.detail = ""
        self.health: dict = {}
        self.last: dict | None = None
        self.history: list[dict] = []
        self._started = threading.Event()
        self._halt = threading.Event()
        self._thread: threading.Thread | None = None

    # -- transport ----------------------------------------------------------
    def _endpoint(self, path: str) -> str:
        return f"http://127.0.0.1:{self.port}{path}"

    def _reachable(self, port: int | None = None, timeout: float = 1.5) -> bool:
        try:
            endpoint = f"http://127.0.0.1:{port or self.port}/health"
            with urllib.request.urlopen(endpoint, timeout=timeout) as reply:
                payload = json.loads(reply.read().decode("utf-8"))
            self.health = {
                "ticks": payload.get("ticks"),
                "utterances": payload.get("utterances"),
                "documents": payload.get("documents"),
                "wishes_accepted": payload.get("wishes_accepted"),
                "refusals": payload.get("refusals"),
            }
            return True
        except (OSError, ValueError, urllib.error.URLError):
            return False

    @staticmethod
    def _port_free(port: int) -> bool:
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
            probe.settimeout(0.4)
            return probe.connect_ex(("127.0.0.1", port)) != 0

    def _stop_tunnel(self) -> None:
        process, self.process = self.process, None
        if process and process.poll() is None:
            process.terminate()
            try:
                process.wait(timeout=3)
            except subprocess.TimeoutExpired:
                process.kill()

    def _start_tunnel(self, port: int | None = None) -> None:
        if self.process and self.process.poll() is None:
            return
        port = port or self.port
        self.port = port
        script = (
            "cd /root; PATH=/usr/bin:/bin exec /usr/bin/ssh -N "
            "-o ExitOnForwardFailure=yes -o ServerAliveInterval=20 "
            f"-L {port}:127.0.0.1:{REMOTE_PORT} -i {KEY} root@{HOST}"
        )
        self.process = subprocess.Popen(
            ["wsl.exe", "-d", DISTRO, "-u", "root", "--", "sh", "-c", script],
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
            creationflags=0x08000000,
        )

    def _read_token(self) -> str:
        result = _wsl("cat /etc/agent/loop.env")
        if result.returncode != 0:
            raise Refused("axis-token-unreadable", (result.stderr or "").strip()[:200])
        for line in result.stdout.splitlines():
            if line.startswith("CUA_LOOP_TOKEN="):
                token = line.split("=", 1)[1].strip()
                if token:
                    return token
        raise Refused("axis-token-absent", "/etc/agent/loop.env has no CUA_LOOP_TOKEN")

    def ensure(self) -> dict:
        # Network and tunnel waits must never hold the state lock: the toast polls state every
        # second and a 90-second tunnel search would make the whole surface look down.
        with self._ensure_lock:
            if self.state == "live" and self._reachable():
                return self.health
            if not self.token:
                self.token = self._read_token()
            if self._reachable():
                self.state, self.detail = "live", ""
                return self.health
            # A stale tunnel can hold the old port without carrying traffic. Take the first
            # free local port instead of killing an unidentified process, then keep retrying.
            for candidate in range(self.port, self.port + 16):
                if self._reachable(candidate):
                    self.port = candidate
                    self.state, self.detail = "live", ""
                    return self.health
                if not self._port_free(candidate):
                    continue
                self._stop_tunnel()
                self._start_tunnel(candidate)
                deadline = time.monotonic() + 6
                while time.monotonic() < deadline:
                    if self._reachable():
                        self.state, self.detail = "live", ""
                        return self.health
                    time.sleep(0.3)
                self._stop_tunnel()
            self.state = "refused"
            self.detail = "axis-unreachable: the Debian loop did not answer through any tunnel port"
            raise Refused("axis-unreachable", self.detail)

    def start(self) -> None:
        if self._thread and self._thread.is_alive():
            return
        self._thread = threading.Thread(target=self._start, daemon=True)
        self._thread.start()

    def _start(self) -> None:
        try:
            while not self._halt.is_set():
                try:
                    self.ensure()
                except Refused as error:
                    with self.lock:
                        self.state, self.detail = "refused", f"{error.code}: {error.detail}"
                self._started.set()
                if self._halt.wait(20):
                    break
        finally:
            self._started.set()

    # -- the host's own answer ----------------------------------------------
    def ask(self, text: str) -> dict:
        text = " ".join(str(text or "").split())
        if not text:
            raise Refused("axis-question-empty", "a question needs words")
        if len(text) > 600:
            raise Refused("axis-question-too-long", str(len(text)))
        self.ensure()
        body = json.dumps({
            "model": "cua-system1",
            "messages": [{"role": "user", "content": text}],
        }).encode("utf-8")
        request = urllib.request.Request(
            self._endpoint("/v1/chat/completions"),
            data=body, method="POST",
            headers={"Authorization": f"Bearer {self.token}",
                     "Content-Type": "application/json"},
        )
        try:
            with urllib.request.urlopen(request, timeout=60) as reply:
                payload = json.loads(reply.read().decode("utf-8"))
        except urllib.error.HTTPError as error:
            raise Refused("axis-http", f"{error.code} {error.read()[:200]!r}") from error
        except (OSError, ValueError, urllib.error.URLError) as error:
            raise Refused("axis-unreachable", str(error)) from error
        choices = payload.get("choices") or []
        message = (choices[0] or {}).get("message", {}) if choices else {}
        answer = str(message.get("content") or "").strip()
        cua = payload.get("cua") or {}
        row = {
            "schema": SCHEMA,
            "at": iso(),
            "question": text,
            "answer": answer,
            "outcome": cua.get("outcome", ""),
            "slots": cua.get("slots", []),
            "missing": cua.get("missing", []),
            "state": "answered" if answer else "kept-quiet",
        }
        with self.lock:
            self.last = row
            self.history = (self.history + [row])[-6:]
        return row

    def state_dict(self) -> dict:
        with self.lock:
            return {
                "schema": SCHEMA,
                "state": self.state,
                "detail": self.detail,
                "endpoint": f"ssh://root@{HOST}:{REMOTE_PORT} -> 127.0.0.1:{self.port}",
                "health": self.health,
                "last": dict(self.last) if self.last else None,
                "history": list(self.history),
            }

    def stop(self) -> None:
        self._halt.set()
        with self.lock:
            process = self.process
            self.process = None
        if process and process.poll() is None:
            process.terminate()
            try:
                process.wait(timeout=3)
            except subprocess.TimeoutExpired:
                process.kill()
